function collectArticleSources(article: (typeof workshopGuideArticles)[number]) {
  return [
    article.shortTitle,
    article.title,
    article.description,
    article.eyebrow,
    article.intentLabel,
    ...article.intro,
    ...article.sections.flatMap((section) => [section.title, ...section.items]),
    ...article.faq.flatMap((item) => [item.q, item.a]),
    ...article.related.map((item) => item.label),
  ];
}

