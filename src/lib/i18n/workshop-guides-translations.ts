function buildExactTranslations() {
  const entries = new Map<string, Partial<Record<WorkshopGuideLocale, string>>>();

  for (const locale of workshopGuideLocaleOrder) {
    const localeGroups = translationsByLocale[locale];

    workshopGuideSourceGroups.forEach((sources, articleIndex) => {
      const translated = localeGroups[articleIndex];
      sources.forEach((source, sourceIndex) => {
        const value = translated[sourceIndex];
        const existing = entries.get(source) ?? {};
        const previous = existing[locale];
        if (previous && previous !== value) {
          throw new Error(`Conflicting ${locale} workshop translation for: ${source}`);
        }
        existing[locale] = value;
        entries.set(source, existing);
      });
    });
  }

  return Object.fromEntries(
    [...entries].map(([source, translations]) => {
      const values = workshopGuideLocaleOrder.map((locale) => {
        const value = translations[locale];
        if (!value) {
          throw new Error(`Missing ${locale} workshop translation for: ${source}`);
        }
        return value;
      }) as unknown as WorkshopGuideTranslationTuple;

      return [source, values];
    }),
  );
}

